"""Tier 2 (integration): real sandbox Cognito user pool + real sandbox RDS. Opt-in only.

Covers what Tier 1 can't: real Cognito-issued tokens and the RDS IAM-auth-token path.
Never runs in CI. Run manually against a sandbox (never prod):

    SUBLETNU_SANDBOX=1 pytest test/integration

Required env:
  SANDBOX_REGION, SANDBOX_USER_POOL_ID, SANDBOX_CLIENT_ID
  SANDBOX_REFRESH_TOKEN      Refresh token from one manual Hosted UI sign-in with a
                             domain-valid Google test account. The pool is Google-only and
                             PreSignUp rejects admin-created users, so this is the "seed".
  DB_HOST, DB_PORT, DB_NAME, DB_USER   Instance endpoint + IAM DB user (read by utils.py).
Optional env:
  SANDBOX_DB_CONNECT_HOST    Where to connect when tunnelling (e.g. localhost via SSM port
                             forwarding). The IAM token is still signed for DB_HOST.
  SANDBOX_ACCESS_TOKEN_TTL_SECONDS     Default 3600 (accessTokenValidity in auth-stack.ts).
  SANDBOX_API_URL            A protected route behind API Gateway's Cognito authorizer.
                             API Gateway isn't built yet; those tests skip until it is.
"""
import base64
import json
import os
import urllib.error
import urllib.request

import pytest

pytestmark = pytest.mark.skipif(
    os.environ.get('SUBLETNU_SANDBOX') != '1',
    reason='opt-in: set SUBLETNU_SANDBOX=1 to run against a real sandbox pool and RDS',
)


def required_env(name: str) -> str:
    """Returns an env var or fails loudly. Input: name. Output: value."""
    value = os.environ.get(name)
    if not value:
        raise RuntimeError(f'{name} is required for the sandbox integration tests')
    return value


def jwt_claims(token: str) -> dict:
    """
    Decodes a JWT payload without verifying it. 
    Input: token 
    Output: claims dict
    """
    payload = token.split('.')[1]
    return json.loads(base64.urlsafe_b64decode(payload + '=' * (-len(payload) % 4)))


def call_api(token: str) -> tuple[int, str]:
    """GETs SANDBOX_API_URL with a bearer token. Input: token. Output: (status, body)."""
    request = urllib.request.Request(os.environ['SANDBOX_API_URL'], headers={'Authorization': token})
    try:
        with urllib.request.urlopen(request, timeout=10) as response:
            return response.status, response.read().decode()
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode()


@pytest.fixture(scope='module')
def cognito():
    """boto3 Cognito client for the sandbox region."""
    import boto3
    return boto3.client('cognito-idp', region_name=required_env('SANDBOX_REGION'))


@pytest.fixture(scope='module')
def access_token(cognito) -> str:
    """Fresh Access token for the seeded user via REFRESH_TOKEN_AUTH (public client, no secret)."""
    result = cognito.initiate_auth(
        ClientId=required_env('SANDBOX_CLIENT_ID'),
        AuthFlow='REFRESH_TOKEN_AUTH',
        AuthParameters={'REFRESH_TOKEN': required_env('SANDBOX_REFRESH_TOKEN')},
    )
    return result['AuthenticationResult']['AccessToken']


def test_seeded_user_obtains_valid_access_token(cognito, access_token: str) -> None:
    claims = jwt_claims(access_token)
    region, pool_id = required_env('SANDBOX_REGION'), required_env('SANDBOX_USER_POOL_ID')
    assert claims['token_use'] == 'access'
    assert claims['client_id'] == required_env('SANDBOX_CLIENT_ID')
    assert claims['iss'] == f'https://cognito-idp.{region}.amazonaws.com/{pool_id}'
    # Cognito itself validates the token (signature, expiry, revocation).
    user = cognito.get_user(AccessToken=access_token)
    assert user['Username'] == claims['username']


def test_access_token_exp_matches_configured_ttl(access_token: str) -> None:
    claims = jwt_claims(access_token)
    expected_ttl = int(os.environ.get('SANDBOX_ACCESS_TOKEN_TTL_SECONDS', '3600'))
    assert claims['exp'] - claims['iat'] == expected_ttl


def test_api_gateway_authorizer_accepts_access_token(access_token: str) -> None:
    if not os.environ.get('SANDBOX_API_URL'):
        pytest.skip('API Gateway + Cognito authorizer not built yet; set SANDBOX_API_URL once it is')
    status, _ = call_api(access_token)
    assert status == 200


def test_api_gateway_authorizer_rejects_tampered_token(access_token: str) -> None:
    if not os.environ.get('SANDBOX_API_URL'):
        pytest.skip('API Gateway + Cognito authorizer not built yet; set SANDBOX_API_URL once it is')
    header, payload, signature = access_token.split('.')
    tampered = '.'.join([header, payload, ('A' if signature[0] != 'A' else 'B') + signature[1:]])
    status, body = call_api(tampered)
    # 401 {"message":"Unauthorized"} is generated by the authorizer itself; the integration Lambda never runs.
    assert status == 401
    assert json.loads(body) == {'message': 'Unauthorized'}


def test_federated_signup_created_users_row(access_token: str) -> None:
    import psycopg2
    import utils

    sub = jwt_claims(access_token)['sub']
    conn = psycopg2.connect(
        host=os.environ.get('SANDBOX_DB_CONNECT_HOST') or required_env('DB_HOST'),
        port=int(required_env('DB_PORT')),
        dbname=required_env('DB_NAME'),
        user=required_env('DB_USER'),
        password=utils.get_auth_token(),  # the IAM-auth path under test
        sslmode='require',
        connect_timeout=5,
    )
    try:
        with conn.cursor() as cur:
            cur.execute('SELECT count(*) FROM users WHERE cognito_sub = %s', (sub,))
            assert cur.fetchone()[0] == 1
    finally:
        conn.close()
