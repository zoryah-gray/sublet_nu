-- SubletNU — /browse fixture data (NOT a migration; never run against a shared DB)
--
-- Fills sublets with a believable, reproducible spread so EXPLAIN ANALYZE
-- exercises the planner's index-vs-seq-scan choice instead of seq-scanning an
-- empty table. Targets the schema as of the latest migration that exists when
-- you run it: coordinates (geography point) + availability_date_range, i.e.
-- after 1791947964406_update-sublets-date-coords. lat/lng and start/end dates
-- are still computed internally and converted on insert, so the generated data
-- matches what the Day 3 version of this file produced. approx_coordinates,
-- approximate_street and title_search are generated by the database. Quarters
-- aren't stored (sublet_quarters was retired in 1793123267633): they're derived
-- from availability_date_range, so the quarter calendar below only shapes the
-- generated dates.
--
-- Run (from the repo root; variables expand inside the container):
--   docker compose exec -T db sh -c 'psql -X -v ON_ERROR_STOP=1 -v rows=5000 -U "$POSTGRES_USER" -d "$POSTGRES_DB"' \
--     < apps/backend/db/seeds/seed-browse.sql
-- or: npm run db:seed -w apps/backend
--
-- Safe to re-run: it first deletes only its own rows (owners with an
-- @seed.subletnu.invalid email, plus everything hanging off their sublets),
-- children before parents because every FK is ON DELETE RESTRICT. It never
-- truncates, so rows you created by hand survive. If you've attached your own
-- match_requests/favorites to seed sublets, the delete fails loudly (RESTRICT)
-- rather than cascading through your data.
--
-- Reproducible: setseed() fixes every random() draw, so the same `rows` value
-- yields the same distribution (UUIDs and created_at still differ per run).

\if :{?rows}
\else
  \set rows 5000
\endif

BEGIN;

-- ─── Remove previous seed rows ───────────────────────────────────────────────
CREATE TEMP TABLE prior_seed_users ON COMMIT DROP AS
  SELECT id FROM users WHERE email LIKE '%@seed.subletnu.invalid';
CREATE TEMP TABLE prior_seed_sublets ON COMMIT DROP AS
  SELECT id FROM sublets WHERE owner_id IN (SELECT id FROM prior_seed_users);

DELETE FROM sublet_images   WHERE sublet_id IN (SELECT id FROM prior_seed_sublets);
DELETE FROM sublets         WHERE id        IN (SELECT id FROM prior_seed_sublets);
DELETE FROM users           WHERE id        IN (SELECT id FROM prior_seed_users);

SELECT setseed(0.42);

-- ─── Owners (~1 per 12 listings; also used as confirmed renters) ────────────
SELECT greatest(:rows / 12, 50) AS owners \gset

INSERT INTO users (name, email, bio, is_public)
SELECT 'Seed Owner ' || n, 'seed-owner-' || n || '@seed.subletnu.invalid', '', n % 3 <> 0
FROM generate_series(1, :owners) AS n;

CREATE TEMP TABLE seed_owners ON COMMIT DROP AS
  SELECT id, substring(email FROM 'seed-owner-(\d+)@')::int AS n
  FROM users WHERE email LIKE '%@seed.subletnu.invalid';
-- Each listing looks its owner up by n; without this key that's rows × owners comparisons.
ALTER TABLE seed_owners ADD PRIMARY KEY (n);

-- ─── Northwestern quarter calendar, two academic years (g = global index) ──
CREATE TEMP TABLE quarter_calendar (g int PRIMARY KEY, quarter text, starts date, ends date) ON COMMIT DROP;
INSERT INTO quarter_calendar VALUES
  (0, 'Fall',   '2026-09-22', '2026-12-12'),
  (1, 'Winter', '2027-01-05', '2027-03-20'),
  (2, 'Spring', '2027-03-30', '2027-06-12'),
  (3, 'Summer', '2027-06-22', '2027-09-04'),
  (4, 'Fall',   '2027-09-21', '2027-12-11'),
  (5, 'Winter', '2028-01-04', '2028-03-18'),
  (6, 'Spring', '2028-03-28', '2028-06-10'),
  (7, 'Summer', '2028-06-20', '2028-09-02');

-- ─── One row of independent random draws per candidate listing ──────────────
-- Drawn once into a table so every derived column below reads fixed values.
-- 3x candidates: points that land outside Evanston are discarded (not clamped —
-- clamping piled a third of all listings onto the lakefront line), and the
-- first :rows survivors are kept.
CREATE TEMP TABLE draws ON COMMIT DROP AS
SELECT n,
       random() AS r_status, random() AS r_draft, random() AS r_type, random() AS r_beds,
       random() AS r_baths, random() AS r_rent, random() AS r_util, random() AS r_util_cost,
       1 - random() AS r_u1, random() AS r_u2, random() AS r_street, random() AS r_house,
       random() AS r_quarter, random() AS r_year, random() AS r_span, random() AS r_jit1,
       random() AS r_jit2, random() AS r_title1, random() AS r_title2, random() AS r_desc1,
       random() AS r_desc2, random() AS r_desc3, random() AS r_created, random() AS r_image,
       random() AS r_owner, random() AS r_roommates, random() AS r_hue
FROM generate_series(1, :rows * 3) AS n;

-- ─── Derive listing attributes ──────────────────────────────────────────────
CREATE TEMP TABLE seed_rows ON COMMIT DROP AS
WITH base AS (
  SELECT d.*,
         gen_random_uuid() AS id,
         CASE WHEN r_status < 0.70 THEN 'public'
              WHEN r_status < 0.85 THEN 'private'
              WHEN r_status < 0.95 THEN 'restricted'
              ELSE 'deleted' END AS display_status,
         CASE WHEN r_type < 0.45 THEN 'entire' ELSE 'private' END AS place_type,
         -- first quarter: Fall 20% · Winter 20% · Spring 25% · Summer 35%; 2026-27 60% / 2027-28 40%
         (CASE WHEN r_year < 0.60 THEN 0 ELSE 4 END)
           + CASE WHEN r_quarter < 0.20 THEN 0 WHEN r_quarter < 0.40 THEN 1
                  WHEN r_quarter < 0.65 THEN 2 ELSE 3 END AS g_first,
         -- span: 1 quarter 60% · 2 quarters 30% · 3 quarters 10%
         CASE WHEN r_span < 0.60 THEN 1 WHEN r_span < 0.90 THEN 2 ELSE 3 END AS span,
         -- Box–Muller around campus, sigma ~1.2 km (1.2/111 deg lat, 1.2/82.4 deg lng at 42°N)
         round((42.0565 + sqrt(-2 * ln(r_u1)) * cos(2 * pi() * r_u2) * 1.2 / 111.0)::numeric, 7)::double precision AS lat,
         round((-87.6753 + sqrt(-2 * ln(r_u1)) * sin(2 * pi() * r_u2) * 1.2 / 82.4)::numeric, 7)::double precision AS lng
  FROM draws d
), in_evanston AS (
  -- Evanston's rough bounding box, west of the lakefront; keep the first :rows that land inside
  SELECT b.*, row_number() OVER (ORDER BY n) AS kept
  FROM base b
  WHERE lat BETWEEN 42.015 AND 42.072 AND lng BETWEEN -87.730 AND -87.668
), shaped AS (
  SELECT b.*,
         least(b.g_first + b.span - 1, 7) AS g_last,
         CASE WHEN place_type = 'entire'
              THEN CASE WHEN r_beds < 0.20 THEN 0 WHEN r_beds < 0.60 THEN 1
                        WHEN r_beds < 0.85 THEN 2 WHEN r_beds < 0.95 THEN 3 ELSE 4 END
              ELSE 2 + floor(r_beds * 3)::int END AS bedroom_count
  FROM in_evanston b
  WHERE kept <= :rows
)
SELECT s.id, s.n, s.display_status, s.place_type, s.bedroom_count, s.lat, s.lng, s.g_first, s.g_last,
       (SELECT id FROM seed_owners o WHERE o.n = 1 + floor(s.r_owner * :owners)::int) AS owner_id,
       CASE WHEN s.display_status = 'restricted'
            THEN (SELECT id FROM seed_owners o WHERE o.n = 1 + (floor(s.r_owner * :owners)::int + 1) % :owners)
       END AS confirmed_renter_id,
       (s.display_status = 'private' AND s.r_draft < 0.667) AS is_draft,
       CASE WHEN s.place_type = 'private' THEN 1 + floor(s.r_roommates * 4)::int END AS roommate_count,
       CASE WHEN s.bedroom_count >= 2 THEN (ARRAY[1, 1.5, 2, 2, 2.5])[1 + floor(s.r_baths * 5)::int]
            ELSE (ARRAY[1, 1, 1.5])[1 + floor(s.r_baths * 3)::int] END::numeric(3,1) AS bathroom_count,
       (round(CASE WHEN s.place_type = 'private' THEN 700 + s.r_rent * 700
                   ELSE least(1100 + s.bedroom_count * 350 + s.r_rent * 600, 3000) END / 25) * 25)::numeric(10,2) AS monthly_rent,
       s.r_util < 0.40 AS utilities_included,
       CASE WHEN s.r_util >= 0.40 THEN (round((50 + s.r_util_cost * 150) / 5) * 5)::numeric(8,2) END AS monthly_utilities_cost,
       (100 + floor(s.r_house * 2900)::int)::text || ' ' ||
         (ARRAY['Hinman Ave','Chicago Ave','Sherman Ave','Orrington Ave','Maple Ave','Ridge Ave',
                'Asbury Ave','Judson Ave','Forest Ave','Elmwood Ave','Davis St','Church St',
                'Clark St','Emerson St','Foster St','Noyes St','Lincoln St','Central St',
                'Dempster St','Main St','Greenwood St','Lake St','Grove St','Sheridan Rd'])[1 + floor(s.r_street * 24)::int] AS street_address,
       CASE WHEN s.lat >= 42.041 THEN '60201' ELSE '60202' END AS zip_code,
       (ARRAY['Sunny','Cozy','Spacious','Bright','Quiet','Modern','Renovated','Charming'])[1 + floor(s.r_title1 * 8)::int] || ' ' ||
         CASE WHEN s.place_type = 'private' THEN 'Private Room'
              WHEN s.bedroom_count = 0 THEN 'Studio'
              ELSE s.bedroom_count || 'BR Apartment' END || ' ' ||
         (ARRAY['Near Campus','by the Lake','in Downtown Evanston','Near the Purple Line',
                'in South Evanston','Near Davis Street','in North Evanston','off Sheridan'])[1 + floor(s.r_title2 * 8)::int] AS title,
       concat_ws(' ',
         (ARRAY['Fully furnished.','Partially furnished.','Unfurnished, bring your own bed.',
                'Furnished with a desk and queen bed.'])[1 + floor(s.r_desc1 * 4)::int],
         (ARRAY['Five-minute walk to campus.','Steps from the lakefront.','Close to the Davis CTA stop.',
                'Quiet street, great for studying.','Near grocery stores and cafes.',
                'Short bike ride to Tech.'])[1 + floor(s.r_desc2 * 6)::int],
         (ARRAY['In-unit laundry.','Air conditioning.','Dishwasher.','Parking available.',
                'Pet friendly.','Shared backyard.'])[1 + floor(s.r_desc3 * 6)::int]) AS description,
       floor(s.r_hue * 360)::int::text AS image_hue,
       now() - (s.r_created * interval '270 days') AS created_at,
       s.r_jit1, s.r_jit2, s.r_image
FROM shaped s;

-- ─── Insert ─────────────────────────────────────────────────────────────────
INSERT INTO sublets (
  id, owner_id, title, street_address, city, state, zip_code, coordinates,
  monthly_rent, bedroom_count, bathroom_count, availability_date_range, description,
  image_hue, place_type, roommate_count, utilities_included, monthly_utilities_cost,
  display_status, confirmed_renter_id, is_draft, deleted_at, created_at, updated_at
)
SELECT r.id, r.owner_id, r.title, r.street_address, 'Evanston', 'IL', r.zip_code,
       ST_Point(r.lng, r.lat, 4326),
       r.monthly_rent, r.bedroom_count, r.bathroom_count,
       daterange(
         first_q.starts + (floor(r.r_jit1 * 13)::int - 5),  -- start: 5 days early .. 7 days late
         last_q.ends    + (floor(r.r_jit2 * 13)::int - 7),  -- end:   7 days early .. 5 days late
         '[]'),
       r.description, r.image_hue, r.place_type, r.roommate_count, r.utilities_included,
       r.monthly_utilities_cost, r.display_status, r.confirmed_renter_id, r.is_draft,
       CASE WHEN r.display_status = 'deleted' THEN r.created_at + interval '30 days' END,
       r.created_at, r.created_at
FROM seed_rows r
JOIN quarter_calendar first_q ON first_q.g = r.g_first
JOIN quarter_calendar last_q  ON last_q.g  = r.g_last;

-- ~80% get a featured image (position 0); a few carry alt text
INSERT INTO sublet_images (sublet_id, url, position, alt)
SELECT r.id, '/stock_images/seed-' || (1 + floor(r.r_image * 12)::int) || '.jpg', 0,
       CASE WHEN r.r_image < 0.30 THEN 'Living area of ' || r.title END
FROM seed_rows r
WHERE r.r_image < 0.80;

COMMIT;

-- Fresh planner statistics, so EXPLAIN reflects this data rather than an empty table.
ANALYZE users;
ANALYZE sublets;
ANALYZE sublet_images;

-- ─── Summary ────────────────────────────────────────────────────────────────
SELECT display_status, count(*) AS sublets FROM sublets GROUP BY 1 ORDER BY 2 DESC;
